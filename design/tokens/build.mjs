// Builds the Imference design tokens (tokens.json) into CSS for every surface.
//
//   node design/tokens/build.mjs            write the outputs
//   node design/tokens/build.mjs --check    exit 1 if an output is stale
//
// Outputs (the site path is skipped when the imference repo is not a sibling):
//   frontend/src/styles/tokens.css   Desktop + Web: light on :root, dark on .dark
//   ../imference/app/web/tokens.css  imference.com: dark on :root, light opt-in
//
// Every variable is prefixed --im-, so it never collides with a framework's own
// names; each product maps its existing names onto these (index.css, site.css).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../..");
const T = JSON.parse(fs.readFileSync(path.join(here, "tokens.json"), "utf8"));

// ---- OKLCH -> sRGB (CSS Color 4 reference math) ----------------------------
function oklchToRgb([L, C, H]) {
  const h = (H * Math.PI) / 180;
  const a = C * Math.cos(h), b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return lin.map((c) => {
    const v = c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(Math.max(c, 0), 1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, v)) * 255);
  });
}
const hex = (rgb) => "#" + rgb.map((c) => c.toString(16).padStart(2, "0")).join("");
function color(v) {
  const rgb = oklchToRgb(v);
  return v.length > 3 && v[3] < 1 ? `rgb(${rgb.join(" ")} / ${+(v[3] * 100).toFixed(1)}%)` : hex(rgb);
}
/** Relative luminance + contrast, used by the --check report. */
function lum(rgb) {
  const [r, g, b] = rgb.map((c) => {
    c /= 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export function contrast(a, b) {
  const [x, y] = [lum(oklchToRgb(a)), lum(oklchToRgb(b))].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

// ---- CSS -------------------------------------------------------------------
const decl = (pairs, indent = "  ") => pairs.map(([k, v]) => `${indent}--im-${k}: ${v};`).join("\n");
const themeVars = (theme) => [
  ...Object.entries(T.color[theme]).map(([k, v]) => [k, color(v)]),
  ...Object.entries(T.shadow[theme]).map(([k, v]) => ["shadow-" + k, v]),
];
const staticVars = [
  ...Object.entries(T.radius).map(([k, v]) => ["radius-" + k, v]),
  ["font-sans", T.font.sans],
  ["font-display", T.font.display],
  ["font-mono", T.font.mono],
  ["font-features", T.font.features],
  ...Object.entries(T.text).flatMap(([k, [s, lh]]) => [["text-" + k, s], ["leading-" + k, lh]]),
  ...Object.entries(T.tracking).map(([k, v]) => ["tracking-" + k, v]),
  ...Object.entries(T.duration).map(([k, v]) => ["duration-" + k, v]),
  ...Object.entries(T.ease).map(([k, v]) => ["ease-" + k, v]),
  ...Object.entries(T.z).map(([k, v]) => ["z-" + k, v]),
  ["focus-width", T.focus.width],
  ["focus-offset", T.focus.offset],
];
const header = (target) => `/* GENERATED by imference-desktop/design/tokens/build.mjs from tokens.json.
   Do not edit: change tokens.json and rebuild. Target: ${target}. */\n`;

const app =
  header("Imference Desktop + Web (light on :root, dark on .dark)") +
  `:root {\n${decl(staticVars)}\n${decl(themeVars("light"))}\n}\n.dark {\n${decl(themeVars("dark"))}\n}\n`;
const site =
  header("imference.com (dark on :root; light opt-in via [data-theme=light])") +
  `:root {\n  color-scheme: dark;\n${decl(staticVars)}\n${decl(themeVars("dark"))}\n}\n[data-theme="light"] {\n  color-scheme: light;\n${decl(themeVars("light"))}\n}\n`;

const outputs = [[path.join(repo, "frontend/src/styles/tokens.css"), app]];
const siteDir = path.resolve(repo, "../imference/app/web");
if (fs.existsSync(siteDir)) outputs.push([path.join(siteDir, "tokens.css"), site]);

// ---- Contrast guard: text tokens must pass WCAG AA on every surface --------
const failures = [];
for (const theme of ["light", "dark"]) {
  const c = T.color[theme];
  for (const bg of ["canvas", "surface", "raised", "sunken"]) {
    for (const [fg, min] of [["fg", 7], ["fg-muted", 4.5], ["fg-subtle", 4.5]]) {
      const r = contrast(c[fg], c[bg]);
      if (r < min) failures.push(`${theme}: ${fg} on ${bg} = ${r.toFixed(2)} (< ${min})`);
    }
  }
  const p = contrast(c["primary-fg"], c.primary);
  if (p < 7) failures.push(`${theme}: primary-fg on primary = ${p.toFixed(2)}`);
}
if (failures.length) {
  console.error("Contrast check failed:\n  " + failures.join("\n  "));
  process.exit(1);
}

const check = process.argv.includes("--check");
let stale = 0;
for (const [file, css] of outputs) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (cur === css) continue;
  if (check) {
    console.error(`stale: ${path.relative(repo, file)} (run node design/tokens/build.mjs)`);
    stale++;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, css);
    console.log(`wrote ${path.relative(repo, file)}`);
  }
}
if (stale) process.exit(1);
if (check) console.log("tokens up to date, contrast AA ok");
